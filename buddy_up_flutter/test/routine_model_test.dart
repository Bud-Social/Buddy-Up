import 'package:buddy_up_flutter/data/models/routine.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('Routine parses the auto_generated flag from the API', () {
    final routine = Routine.fromJson({
      'id': 'r1',
      'auto_generated': true,
    });
    expect(routine.autoGenerated, isTrue);
    expect(routine.isActive, isTrue);
  });

  test('Routine defaults auto_generated to false', () {
    final routine = Routine.fromJson({'id': 'r2'});
    expect(routine.autoGenerated, isFalse);
  });
}
