/// Everything the composer needs to remember from the studio flow.
class VideoStudioResult {
  final int trimStartMs;
  final int trimEndMs;
  final String? soundId;
  final double? soundVolume; // 0..1, null when original audio
  final List<CaptionSegment> captions;
  final String visibility;
  final bool commentsEnabled;
  /// Cover frame offset in seconds (0 = start of clip).
  final double? coverOffsetSec;
  /// Creative-studio edit metadata (captions style, text overlays, stickers…)
  /// shipped with the post as media[].edit_meta.
  final Map<String, dynamic>? editMeta;

  const VideoStudioResult({
    required this.trimStartMs,
    required this.trimEndMs,
    this.soundId,
    this.soundVolume,
    this.captions = const [],
    required this.visibility,
    required this.commentsEnabled,
    this.coverOffsetSec,
    this.editMeta,
  });
}

/// Studio the composer routes to after a video is picked. Steps:
/// trim → sound → audience → cover/publish. The cover is generated by the
/// upload pipeline (Cloudinary eager) and only surfaced here once known.
class VideoStudioScreen extends ConsumerStatefulWidget {
  final ComposerMedia video;
  final String initialVisibility;
  /// Client-generated id for this clip instance — captions are saved/restored
  /// per item id via ``POST/GET /feed/studio/captions/<item_id>/``.
  final String? itemId;

  const VideoStudioScreen({
    super.key,
    required this.video,
    this.initialVisibility = 'public',
    this.itemId,
  });

  @override
  ConsumerState<VideoStudioScreen> createState() => _VideoStudioScreenState();
}

class _VideoStudioScreenState extends ConsumerState<VideoStudioScreen> {
  Player? _player;
  VideoController? _controller;
  StreamSubscription<Duration>? _positionSub;

  int _durationMs = 0;
  int _trimStartMs = 0;
  int _trimEndMs = 0;
  bool _loopPreview = false;

  Sound? _selectedSound;
  double _soundVolume = 100;
  late String _visibility;
  bool _commentsEnabled = true;

  List<CaptionSegment> _captions = const [];
  Map<String, dynamic>? _editMeta;
  double? _coverOffsetSec;
  bool _transcribing = false;
  String? _transcribeError;
  final Map<String, TextEditingController> _captionCtrls = {};

  static const int _maxTrimMs = 180 * 1000;

  static const Map<String, dynamic> _defaultCaptionStyle = {
    'preset': 'classic',
    'size': 0.9,
    'color': '#FFFFFF',
    'bg': 'block',
    'placement': 'bottom',
  };

  @override
  void initState() {
    super.initState();
    _visibility = widget.initialVisibility;
    AnalyticsService.instance.track(
      'create.started',
      surface: 'composer_studio',
      objectType: 'video',
      objectId: widget.video.name,
    );
    _setupPlayer();
    _editMeta = {'captions_style': Map<String, dynamic>.from(_defaultCaptionStyle)};
    _coverOffsetSec = 0.0;
    Future.microtask(
      () => ref.read(soundsProvider.notifier).load(ordering: 'trending'),
    );
    if (widget.itemId != null) {
      _loadSavedCaptions();
    }
  }

  void _setupPlayer() {
    final player = Player();
    _player = player;
    _controller = VideoController(player);
    _positionSub = player.stream.position.listen((p) {
      if (!mounted) return;
      final end = _trimEndMs;
      if (_loopPreview && end > _trimStartMs) {
        if (p.inMilliseconds >= end) {
          player.seek(Duration(milliseconds: _trimStartMs));
        }
      }
    });
    player.stream.duration.listen((d) {
      if (!mounted || d.inMilliseconds <= 0) return;
      setState(() {
        _durationMs = d.inMilliseconds;
        final end = _durationMs < _maxTrimMs ? _durationMs : _maxTrimMs;
        if (_trimEndMs == 0 || _trimEndMs > end) _trimEndMs = end;
      });
    });
    player.open(Media(widget.video.path), play: false);
  }

  @override
  void dispose() {
    _positionSub?.cancel();
    _player?.dispose();
    for (final c in _captionCtrls.values) {
      c.dispose();
    }
    super.dispose();
  }

  Future<void> _openTrimSheet() async {
    if (_durationMs <= 0) {
      showToast(context, 'Video is still loading — try again in a moment');
      return;
    }
    final result = await showModalBottomSheet<({int start, int end})>(
      context: context,
      backgroundColor: BuddyColors.surface,
      isScrollControlled: true,
      builder: (_) => _TrimSheet(
        durationMs: _durationMs,
        initialStartMs: _trimStartMs,
        initialEndMs: _trimEndMs,
        maxTrimMs: _maxTrimMs,
      ),
    );
    if (result == null) return;
    if (!mounted) return;
    setState(() {
      _trimStartMs = result.start;
      _trimEndMs = result.end;
    });
    AnalyticsService.instance.track(
      'create.trim_set',
      surface: 'composer_studio',
      objectType: 'video',
      objectId: widget.video.name,
      properties: {'trim_start_ms': _trimStartMs, 'trim_end_ms': _trimEndMs},
    );
    showToast(context, 'Trim saved', type: ToastType.success);
  }

  Future<void> _openSoundSheet() async {
    final result = await showModalBottomSheet<({Sound? sound, double volume})>(
      context: context,
      backgroundColor: BuddyColors.surface,
      isScrollControlled: true,
      builder: (_) => _SoundSheet(initialSelectedSoundId: _selectedSound?.id),
    );
    if (result == null) return;
    if (!mounted) return;
    setState(() {
      _selectedSound = result.sound;
      _soundVolume = result.volume;
    });
    if (result.sound != null) {
      ref.read(soundsProvider.notifier).markUsed(result.sound!.id);
      AnalyticsService.instance.track(
        'create.sound_added',
        surface: 'composer_studio',
        objectType: 'sound',
        objectId: result.sound!.id,
        properties: {
          'sound_name': result.sound!.name,
          'volume': result.volume.round(),
        },
      );
    }
  }

  Future<void> _openAudienceSheet() async {
    final result =
        await showModalBottomSheet<({String visibility, bool commentsEnabled})>(
          context: context,
          backgroundColor: BuddyColors.surface,
          builder: (_) => _AudienceSheet(
            initialVisibility: _visibility,
            initialCommentsEnabled: _commentsEnabled,
          ),
        );
    if (result == null) return;
    if (!mounted) return;
    setState(() {
      _visibility = result.visibility;
      _commentsEnabled = result.commentsEnabled;
    });
  }

  void _toggleLoopPreview() async {
    final player = _player;
    if (player == null) return;
    setState(() => _loopPreview = !_loopPreview);
    if (_loopPreview) {
      await player.seek(Duration(milliseconds: _trimStartMs));
      await player.play();
    } else {
      await player.pause();
    }
  }

  void _done() {
    Navigator.of(context).pop(
      VideoStudioResult(
        trimStartMs: _trimStartMs,
        trimEndMs: _trimEndMs,
        soundId: _selectedSound?.id,
        soundVolume: _selectedSound == null ? null : _soundVolume / 100,
        captions: _captions
            .where((s) => s.text.trim().isNotEmpty && s.endMs > s.startMs)
            .toList(),
        visibility: _visibility,
        commentsEnabled: _commentsEnabled,
        coverOffsetSec: _coverOffsetSec,
        editMeta: _editMeta,
      ),
    );
  }

  /// In-studio auto-captions: transcribe the picked clip and let the user
  /// edit the lines before returning to the composer.
  Future<void> _generateCaptions() async {
    if (_transcribing) return;
    setState(() {
      _transcribing = true;
      _transcribeError = null;
    });
    try {
      final file = File(widget.video.path);
      if (!await file.exists()) {
        throw Exception('Clip file is no longer available.');
      }
      final raw = await ref
          .read(feedRepositoryProvider)
          .transcribeStudioMedia(file);
      final data = (raw['data'] as Map<String, dynamic>?) ?? {};
      final segments = data['segments'];
      final parsed = <CaptionSegment>[];
      if (segments is List) {
        for (final s in segments) {
          if (s is! Map) continue;
          final text = (s['text'] as String? ?? '').trim();
          if (text.isEmpty) continue;
          parsed.add(
            CaptionSegment(
              startMs: (s['start_ms'] as num?)?.toInt() ?? 0,
              endMs: (s['end_ms'] as num?)?.toInt() ?? 0,
              text: text,
            ),
          );
        }
      }
      if (!mounted) return;
      setState(() => _captions = parsed);
      AnalyticsService.instance.track(
        'create.studio_captions_generated',
        surface: 'composer_studio',
        objectType: 'video',
        objectId: widget.video.name,
        properties: {'segments': parsed.length},
      );
      showToast(
        context,
        parsed.isEmpty
            ? 'No speech detected'
            : '${parsed.length} caption lines ready',
        type: ToastType.success,
      );
    } catch (e) {
      if (!mounted) return;
      setState(
        () => _transcribeError =
            'Transcription failed — try again or add captions manually.',
      );
    } finally {
      if (mounted) setState(() => _transcribing = false);
    }
  }

  void _removeCaption(int index) {
    setState(() => _captions = List.of(_captions)..removeAt(index));
    _syncCaptionCtrls();
    _persistCaptions();
  }

  /// Load captions saved for this clip item (if any) from the backend.
  Future<void> _loadSavedCaptions() async {
    if (widget.itemId == null) return;
    try {
      final raw = await ref
          .read(feedRepositoryProvider)
          .getStudioCaptions(widget.itemId!);
      final data = (raw['data'] as Map<String, dynamic>?) ?? {};
      final segments = data['captions'];
      final parsed = <CaptionSegment>[];
      if (segments is List) {
        for (final s in segments) {
          if (s is! Map) continue;
          final text = (s['text'] as String? ?? '').trim();
          if (text.isEmpty) continue;
          parsed.add(
            CaptionSegment(
              startMs: (s['start_ms'] as num?)?.toInt() ?? 0,
              endMs: (s['end_ms'] as num?)?.toInt() ?? 0,
              text: text,
            ),
          );
        }
      }
      if (!mounted) return;
      setState(() {
        _captions = parsed;
        _syncCaptionCtrls();
      });
    } catch (_) {
      // Captions are optional — start empty if the backend is unreachable.
    }
  }

  /// Persist the current captions for this clip item (fire and forget).
  Future<void> _persistCaptions() async {
    if (widget.itemId == null) return;
    try {
      await ref.read(feedRepositoryProvider).saveStudioCaptions(
        widget.itemId!,
        {
          'captions': _captions
              .map((c) => {
                    'start_ms': c.startMs,
                    'end_ms': c.endMs,
                    'text': c.text,
                  })
              .toList(),
        },
      );
    } catch (e) {
      if (mounted) {
      showToast(
        context,
        'Captions saved locally — they will publish with the video.',
        type: ToastType.info,
      );
      }
    }
  }

  void _setCaptionText(int index, String text) {
    setState(() {
      _captions = [
        for (var i = 0; i < _captions.length; i++)
          i == index
              ? _captions[i].copyWith(text: text)
              : _captions[i]
      ];
    });
    _syncCaptionCtrls();
    _persistCaptions();
  }

  void _setCaptionTiming(int index, {int? startMs, int? endMs}) {
    setState(() {
      _captions = [
        for (var i = 0; i < _captions.length; i++)
          i == index
              ? _captions[i].copyWith(
                    startMs: startMs ?? _captions[i].startMs,
                    endMs: endMs ?? _captions[i].endMs,
                  )
              : _captions[i]
      ];
    });
    _syncCaptionCtrls();
    _persistCaptions();
  }

  void _addCaptionLine() {
    var start = _captions.isEmpty ? 0 : _captions.last.endMs;
    if (_durationMs > 0 && start > _durationMs - 1000) {
      start = (_durationMs - 1000).clamp(0, _durationMs);
    }
    final end = (start + 3000).clamp(0, _durationMs);
    setState(() {
      _captions = [
        ..._captions,
        CaptionSegment(startMs: start, endMs: end, text: ''),
      ];
    });
    _syncCaptionCtrls();
    _persistCaptions();
    showToast(
      context,
      'Caption line added at ${_fmt(start)} — edit the text and timing.',
      type: ToastType.success,
    );
  }

  void _syncCaptionCtrls() {
    final keys = <String>{};
    for (var i = 0; i < _captions.length; i++) {
      keys.addAll(['${i}t', '${i}s', '${i}e']);
      _captionCtrls.putIfAbsent(
        '${i}t',
        () => TextEditingController(text: _captions[i].text),
      );
      _captionCtrls.putIfAbsent(
        '${i}s',
        () => TextEditingController(text: _captions[i].startMs.toString()),
      );
      _captionCtrls.putIfAbsent(
        '${i}e',
        () => TextEditingController(text: _captions[i].endMs.toString()),
      );
    }
    for (var i = 0; i < _captions.length; i++) {
      _captionCtrls['${i}t']!.text = _captions[i].text;
      _captionCtrls['${i}s']!.text = _captions[i].startMs.toString();
      _captionCtrls['${i}e']!.text = _captions[i].endMs.toString();
    }
    _captionCtrls.removeWhere((k, _) => !keys.contains(k));
  }

  TextEditingController _captionTextCtrl(int i) =>
      _captionCtrls.putIfAbsent(
        '${i}t',
        () => TextEditingController(text: _captions[i].text),
      );

  TextEditingController _captionStartCtrl(int i) =>
      _captionCtrls.putIfAbsent(
        '${i}s',
        () => TextEditingController(text: _captions[i].startMs.toString()),
      );

  TextEditingController _captionEndCtrl(int i) =>
      _captionCtrls.putIfAbsent(
        '${i}e',
        () => TextEditingController(text: _captions[i].endMs.toString()),
      );

  void _openCaptionStyleSheet() {
    final style = Map<String, dynamic>.from(_editMeta?['captions_style'] ?? _defaultCaptionStyle);
    var placement = style['placement'] as String? ?? 'bottom';
    var sizeKey = (style['size'] as num?)?.toDouble() ?? 1.0;
    var sizeLabel = sizeKey < 0.9 ? 'Small' : sizeKey > 1.1 ? 'Large' : 'Medium';
    showModalBottomSheet(
      context: context,
      backgroundColor: BuddyColors.surface,
      isScrollControlled: true,
      builder: (_) => SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text(
                'Caption style',
                style: TextStyle(
                  color: BuddyColors.textPrimary,
                  fontWeight: FontWeight.w600,
                  fontSize: 16,
                ),
              ),
              const SizedBox(height: 12),
              const Text(
                'Position',
                style: TextStyle(
                  color: BuddyColors.textSecondary,
                  fontSize: 12,
                ),
              ),
              const SizedBox(height: 6),
              Wrap(
                spacing: 8,
                children: ['bottom', 'center', 'top'].map((p) {
                  return ChoiceChip(
                    label: Text(p[0].toUpperCase() + p.substring(1)),
                    selected: placement == p,
                    onSelected: (_) => placement = p,
                  );
                }).toList(),
              ),
              const SizedBox(height: 12),
              const Text(
                'Size',
                style: TextStyle(
                  color: BuddyColors.textSecondary,
                  fontSize: 12,
                ),
              ),
              const SizedBox(height: 6),
              Wrap(
                spacing: 8,
                children: ['Small', 'Medium', 'Large'].map((label) {
                  final value = {'Small': 0.8, 'Medium': 1.0, 'Large': 1.3}[label]!;
                  return ChoiceChip(
                    label: Text(label),
                    selected: sizeLabel == label,
                    onSelected: (_) => sizeKey = value,
                  );
                }).toList(),
              ),
              const SizedBox(height: 16),
              SizedBox(
                width: double.infinity,
                child: FilledButton(
                  style: FilledButton.styleFrom(
                    backgroundColor: BuddyColors.green,
                    foregroundColor: BuddyColors.black,
                  ),
                  onPressed: () {
                    setState(() {
                      _editMeta = {
                        ...?_editMeta,
                        'captions_style': {
                          'preset': 'classic',
                          'size': sizeKey,
                          'color': '#FFFFFF',
                          'bg': 'block',
                          'placement': placement,
                        }
                      };
                    });
                    Navigator.of(context).pop();
                  },
                  child: const Text('Save'),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  /// Open a tiny overlay editor so captions/text stickers are placed relative
  /// to the video frame (bottom / center / top) instead of covering it.
  void _openOverlayEditor() {
    var kind = 'text';
    var content = '';
    var position = 'bottom';
    var sizeKey = 1.0;
    const startMs = 0;
    showModalBottomSheet(
      context: context,
      backgroundColor: BuddyColors.surface,
      isScrollControlled: true,
      builder: (_) => SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text(
                'Add overlay',
                style: TextStyle(
                  color: BuddyColors.textPrimary,
                  fontWeight: FontWeight.w600,
                  fontSize: 16,
                ),
              ),
              const SizedBox(height: 12),
              const Text(
                'Kind',
                style: TextStyle(
                  color: BuddyColors.textSecondary,
                  fontSize: 12,
                ),
              ),
              const SizedBox(height: 6),
              Wrap(
                spacing: 8,
                children: [
                  ('text', 'Text caption'),
                  ('emoji', 'Emoji / sticker'),
                ].map((entry) {
                  return ChoiceChip(
                    label: Text(entry.$2),
                    selected: kind == entry.$1,
                    onSelected: (_) => kind = entry.$1,
                  );
                }).toList(),
              ),
              const SizedBox(height: 12),
              TextField(
                decoration: const InputDecoration(
                  hintText: 'Caption or emoji text',
                  border: OutlineInputBorder(),
                ),
                onChanged: (v) => content = v,
              ),
              const SizedBox(height: 12),
              const Text(
                'Position on the video',
                style: TextStyle(
                  color: BuddyColors.textSecondary,
                  fontSize: 12,
                ),
              ),
              const SizedBox(height: 6),
              Wrap(
                spacing: 8,
                children: ['bottom', 'center', 'top'].map((p) {
                  return ChoiceChip(
                    label: Text(p[0].toUpperCase() + p.substring(1)),
                    selected: position == p,
                    onSelected: (_) => position = p,
                  );
                }).toList(),
              ),
              const SizedBox(height: 12),
              const Text(
                'Size',
                style: TextStyle(
                  color: BuddyColors.textSecondary,
                  fontSize: 12,
                ),
              ),
              const SizedBox(height: 6),
              Wrap(
                spacing: 8,
                children: ['Small', 'Medium', 'Large'].map((label) {
                  return ChoiceChip(
                    label: Text(label),
                    selected: sizeKey == {'Small': 0.8, 'Medium': 1.0, 'Large': 1.3}[label],
                    onSelected: (_) => sizeKey = {'Small': 0.8, 'Medium': 1.0, 'Large': 1.3}[label]!,
                  );
                }).toList(),
              ),
              const SizedBox(height: 16),
              SizedBox(
                width: double.infinity,
                child: FilledButton(
                  style: FilledButton.styleFrom(
                    backgroundColor: BuddyColors.green,
                    foregroundColor: BuddyColors.black,
                  ),
                  onPressed: content.trim().isEmpty
                      ? null
                      : () {
                          final y = {'bottom': 80, 'center': 50, 'top': 20}[position]!;
                          final overlay = {
                            'text': content.trim(),
                            'start_ms': startMs,
                            'end_ms': startMs + 4000,
                            'x': 50,
                            'y': y,
                            'size': sizeKey,
                            'color': '#FFFFFF',
                            'effect': 'shadow',
                            'bg': 'block',
                            'font': 'classic',
                          };
                          setState(() {
                            final overlays = List<Map<String, dynamic>>.from(
                                (_editMeta?['text_overlays'] as List?)
                                    ?.cast<Map<String, dynamic>>() ??
                                <Map<String, dynamic>>[]);
                            overlays.add(overlay);
                            _editMeta = {
                              ...?_editMeta,
                              'text_overlays': overlays,
                            };
                          });
                          Navigator.of(context).pop();
                          showToast(
                            context,
                            'Overlay added — it renders relative to the video frame.',
                            type: ToastType.success,
                          );
                        },
                  child: const Text('Add overlay'),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  String _fmt(int ms) {
    final total = (ms / 1000).round();
    return '${total ~/ 60}:${(total % 60).toString().padLeft(2, '0')}';
  }

